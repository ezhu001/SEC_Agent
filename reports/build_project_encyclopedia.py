"""Generate source-derived encyclopedia appendices without importing the app."""
from __future__ import annotations

import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / 'reports/PROJECT_ENCYCLOPEDIA.md'
BASE = ROOT / 'src/financial_filing_agent'
BEGIN = '<!-- BEGIN GENERATED REFERENCE -->'
END = '<!-- END GENERATED REFERENCE -->'


def compact(value):
    return ast.unparse(value).replace('\n', ' ')


def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', '<br>')


def link(path, line=None, label=None):
    relative = path.relative_to(ROOT).as_posix()
    target = '../' + relative
    if line:
        target += f':{line}'
    return f'[{label or relative}]({target})'


def definitions(body, prefix=''):
    for node in body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            qualified = prefix + node.name
            yield qualified, node
            yield from definitions(node.body, qualified + '.')


def literal(node):
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError):
        return compact(node)


def assignments(tree):
    return {node.targets[0].id: node.value for node in tree.body
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)}


def main():
    paths = sorted(BASE.rglob('*.py'))
    support = [ROOT / 'app.py']
    for directory in ('evaluation', 'tests', 'scripts'):
        support.extend(sorted((ROOT / directory).rglob('*.py')))
    paths = [p for p in paths + support if '__pycache__' not in p.parts]
    trees = {p: ast.parse(p.read_text(encoding='utf-8'), filename=str(p)) for p in paths}
    manifest = [{'path': p.relative_to(ROOT).as_posix(),
                 'sha256': hashlib.sha256(p.read_bytes()).hexdigest(),
                 'lines': len(p.read_text(encoding='utf-8').splitlines()),
                 'symbols': [{'name': name, 'line': node.lineno,
                              'kind': 'class' if isinstance(node, ast.ClassDef) else 'function'}
                             for name, node in definitions(trees[p].body)]}
                for p in paths]
    sections = []
    add = sections.append
    add('## Appendix A. Complete Python source inventory\n')
    add('All application Python modules, entry point, evaluation helpers, tests, and repository scripts are listed below. Empty `__init__.py` files provide package boundaries. Files under `__pycache__`, generated bytecode, and environment directories are excluded; incidental files there are not treated as intentional runtime components.\n')
    add('| Source | Lines | Classes/functions (including nested definitions) |\n|---|---:|---:|')
    for p, item in zip(paths, manifest):
        add(f'| {link(p)} | {item["lines"]} | {len(item["symbols"])} |')

    add('\n## Appendix B. Exact settings and their validation declarations\n')
    add('These are source declarations, not the contents of the user\'s environment or `.env`. Settings use the `FFA_` environment prefix and `.env` loading. Explicit constructor/config values and UI/CLI overrides affect the effective run; inspect the recorded run configuration for actual values.\n')
    settings = trees[BASE / 'config/settings.py']
    klass = next(n for n in settings.body if isinstance(n, ast.ClassDef) and n.name == 'Settings')
    add('| Setting | Type | Source default / constraints |\n|---|---|---|')
    for n in klass.body:
        if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
            add(f'| `{n.target.id}` | `{cell(compact(n.annotation))}` | `{cell(compact(n.value))}` |')

    add('\n## Appendix C. Exact financial registries\n')
    form = assignments(trees[BASE / 'config/formulas.py'])['FORMULAS']
    add('### C.1 Formula entries\n')
    add('| Formula ID | Components | Periods | Unit | Definition |\n|---|---|---:|---|---|')
    for key, value in zip(form.keys, form.values):
        args = [literal(a) for a in value.args]
        add(f'| `{literal(key)}` | `{cell(args[0])}` | {args[1]} | {args[2]} | {cell(args[3])} |')
    add('\n### C.2 Canonical concept entries\n')
    concepts = literal(assignments(trees[BASE / 'config/financial_concepts.py'])['CONCEPTS'])
    add('| Concept | Statement | Reported label aliases | Supported XBRL local names |\n|---|---|---|---|')
    for name, (statement, aliases, tags) in concepts.items():
        add(f'| `{name}` | {statement} | {cell("; ".join(aliases))} | {cell("; ".join(tags))} |')

    add('\n## Appendix D. Complete declared data-field dictionary\n')
    add('Fields below are transcribed from annotations. `Record` supplies extra-field rejection and nonfinite-number policy to its derived Pydantic records. `RunState` is a TypedDict, not a Pydantic runtime validator. Class validators are listed in the symbol reference and implemented in the linked files.\n')
    for p in sorted((BASE / 'schemas').glob('*.py')):
        for name, n in definitions(trees[p].body):
            if not isinstance(n, ast.ClassDef):
                continue
            add(f'### D. {name}\n')
            add(f'Source: {link(p, n.lineno)}. Bases: `{cell(", ".join(compact(b) for b in n.bases) or "none")}`.\n')
            fields = [a for a in n.body if isinstance(a, ast.AnnAssign)]
            if not fields:
                add('No annotated fields declared in this class.\n')
                continue
            add('| Field | Type | Default / constraints |\n|---|---|---|')
            for f in fields:
                add(f'| `{compact(f.target)}` | `{cell(compact(f.annotation))}` | `{cell(compact(f.value) if f.value else "required / no class default")}` |')
            add('')

    add('\n## Appendix E. Exact graph and verification-check maps\n')
    graph = trees[BASE / 'graph/workflow.py']
    allowed = next(n.value for n in ast.walk(graph) if isinstance(n, ast.Assign)
                   and any(isinstance(t, ast.Name) and t.id == 'allowed' for t in n.targets))
    add('| Working node | Allowed conditional destinations |\n|---|---|')
    for name, dest in literal(allowed).items():
        add(f'| `{name}` | {", ".join("`" + d + "`" for d in dest)} |')
    add('\nThe fixed START edge is `validate_request`; the fixed `finish` edge is END. Destinations represent graph authorization, not a promise every branch will be exercised.\n')
    contract = assignments(trees[BASE / 'agents/verification_contract.py'])
    for key in ('CHECK_FIELDS', 'CHECK_DEFINITIONS', 'ERROR_CHECKS'):
        add(f'### E. {key}\n\n```python\n{ast.unparse(contract[key])}\n```\n')

    add('\n## Appendix F. Actual system prompts, verbatim\n')
    add('These source strings are the current role instructions. The decoder also receives the per-call payload and schema. The actual historical request can differ if a run used an earlier source snapshot; inspect its audit.\n')
    prompt_values = {}
    for name, value in assignments(trees[BASE / 'config/prompts.py']).items():
        if isinstance(value, ast.Constant):
            prompt_values[name] = value.value
        elif isinstance(value, ast.BinOp) and isinstance(value.op, ast.Add):
            prompt_values[name] = prompt_values[value.left.id] + ast.literal_eval(value.right)
    for role in ('PLANNER', 'VERIFIER', 'CORRECTOR'):
        add(f'### F. {role}\n\n```text\n{prompt_values[role]}\n```\n')

    add('\n## Appendix G. Source-symbol encyclopedia\n')
    add('This index covers every class, function, method, and directly nested definition in the inventoried files. Signatures include defaults and annotations. Calls are static syntax references found within each definition (including nested bodies); they do not prove every call runs, reveal full dispatch, or grant the model access to those functions. A long call list shows its first 24 distinct names and total size. Source links are authoritative for complete implementation.\n')
    for p in paths:
        defs = list(definitions(trees[p].body))
        if not defs:
            continue
        add(f'### Module: `{p.relative_to(ROOT).as_posix()}`\n')
        module_doc = ast.get_docstring(trees[p])
        if module_doc:
            add(module_doc + '\n')
        imports = []
        for n in trees[p].body:
            if isinstance(n, ast.ImportFrom):
                imports.append('.' * n.level + (n.module or ''))
            elif isinstance(n, ast.Import):
                imports.extend(a.name for a in n.names)
        if imports:
            add('**Direct top-level import dependencies:** ' + ', '.join(f'`{v}`' for v in dict.fromkeys(imports)) + '.\n')
        for name, node in defs:
            add(f'#### `{name}`\n')
            add(f'**Implementation:** {link(p, node.lineno, f"line {node.lineno}")}.')
            if isinstance(node, ast.ClassDef):
                bases = ', '.join(compact(b) for b in node.bases)
                add(f'**Kind:** class. **Bases:** `{bases or "none"}`.\n')
            else:
                add(f'**Signature:** `{name}({cell(ast.unparse(node.args))})`' + (f' → `{cell(compact(node.returns))}`' if node.returns else '') + '.\n')
            doc = ast.get_docstring(node)
            if doc:
                add('**Declared purpose:** ' + doc.replace('\n', ' ') + '\n')
            decorators = [compact(d) for d in node.decorator_list]
            if decorators:
                add('**Decorators / validation hooks:** ' + ', '.join(f'`{cell(d)}`' for d in decorators) + '.\n')
            if not isinstance(node, ast.ClassDef):
                calls = sorted(set(compact(n.func) for n in ast.walk(node) if isinstance(n, ast.Call)))
                if calls:
                    add('**Static calls:** ' + ', '.join(f'`{cell(c)}`' for c in calls[:24]) +
                        (f' … ({len(calls)} distinct call expressions).' if len(calls) > 24 else '.') + '\n')
                raises = sorted(set(compact(n.exc.func if isinstance(n.exc, ast.Call) else n.exc)
                                    for n in ast.walk(node) if isinstance(n, ast.Raise) and n.exc))
                if raises:
                    add('**Explicitly raised exception expressions:** ' + ', '.join(f'`{cell(r)}`' for r in raises) + '.\n')
            else:
                members = [a.name for a in node.body if isinstance(a, (ast.FunctionDef, ast.AsyncFunctionDef))]
                if members:
                    add('**Declared methods:** ' + ', '.join(f'`{m}`' for m in members) + '.\n')

    add('\n## Appendix H. Snapshot manifest and verification method\n')
    add(f'This reference inventories **{len(paths)} Python files** and **{sum(len(x["symbols"]) for x in manifest)} definitions**. All files were parsed with the Python AST parser. A machine-readable manifest stores each file\'s SHA-256, line count, and symbol locations: [PROJECT_SOURCE_MANIFEST.json](PROJECT_SOURCE_MANIFEST.json). Empty package files are included; generated bytecode and virtual environments are excluded.\n')
    add('Regenerate the appendices after code changes with `python reports/build_project_encyclopedia.py` from the repository root. The manual body should also be reviewed when behavior changes. The generator reads only repository Python sources, does not import the application, does not execute tests/models, and does not read secret configuration.\n')
    original = REPORT.read_text(encoding='utf-8')
    before, remainder = original.split(BEGIN, 1)
    _, after = remainder.split(END, 1)
    report = before + BEGIN + '\n\n' + '\n'.join(sections) + '\n' + END + after
    REPORT.write_text(report, encoding='utf-8')
    (ROOT / 'reports/PROJECT_SOURCE_MANIFEST.json').write_text(json.dumps({
        'scope': 'Application package, app.py, evaluation, tests, scripts; source-only documentation snapshot',
        'files': manifest,
    }, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'file': str(REPORT), 'words': len(report.split()), 'source_files': len(paths),
                      'definitions': sum(len(x['symbols']) for x in manifest)}, indent=2))


if __name__ == '__main__':
    main()
